#!/usr/bin/env python3
"""Build a kernel config fragment that forces a set of drivers built in.

usage: kfrag.py <kernel src> <base .config> <modules.builtin> <modlist> <extra.config> <out.config>

  <base .config>    the distribution config the fragment is applied to
  <modules.builtin> from a kernel build where the drivers were built in
  <modlist>         module names (one per line), e.g. drivers bound at boot
  <extra.config>    hand-written options to include as well

Maps each module to its CONFIG_ symbol through the kernel Makefiles, then
merges base + fragment with olddefconfig repeatedly, adding the options
that block a requested =y (from its Kconfig "depends on"), until every
requested option sticks or no more progress is made.
"""
import os
import re
import subprocess
import sys
import tempfile

src, base, builtin, modlist, extra, out = (os.path.abspath(p) for p in sys.argv[1:7])


def obj_to_symbol(path):
    """drivers/spi/spi-geni-qcom.ko -> SPI_QCOM_GENI (via the Makefile)."""
    d, f = os.path.split(path.removeprefix('kernel/'))
    obj = f[:-3] + '.o'
    while d:
        mk = os.path.join(src, d, 'Makefile')
        if os.path.exists(mk):
            text = open(mk).read().replace('\\\n', ' ')
            for line in text.splitlines():
                m = re.match(r'\s*obj-\$\(CONFIG_(\w+)\)\s*[+:]?=(.*)', line)
                if m and re.search(rf'(^|\s){re.escape(obj)}(\s|$)', m.group(2)):
                    return m.group(1)
            # the object may be listed relative to a parent directory
        obj = os.path.basename(d) + '/' + obj
        d = os.path.dirname(d)
    return None


def load(path):
    vals = {}
    for line in open(path):
        m = re.match(r'^CONFIG_(\w+)=(.*)$', line)
        if m:
            vals[m.group(1)] = m.group(2)
        m = re.match(r'^# CONFIG_(\w+) is not set', line)
        if m:
            vals[m.group(1)] = 'n'
    return vals


def kconfig_deps():
    """symbol -> identifiers in its 'depends on' lines (all definitions)."""
    deps = {}
    for root, _, files in os.walk(src):
        for f in files:
            if not f.startswith('Kconfig'):
                continue
            sym = None
            for line in open(os.path.join(root, f), errors='replace'):
                m = re.match(r'^\s*(?:menu)?config\s+(\w+)', line)
                if m:
                    sym = m.group(1)
                    continue
                m = re.match(r'^\s*depends on\s+(.*)', line)
                if m and sym:
                    deps.setdefault(sym, set()).update(re.findall(r'\b[A-Z][A-Z0-9_]+\b', m.group(1)))
                elif re.match(r'^\s*(endmenu|endif|menu |choice|if )', line):
                    sym = None
    return deps


modmap = {}
for line in open(builtin):
    p = line.strip()
    modmap[os.path.basename(p)[:-3].replace('-', '_')] = p

wanted, unmapped = {}, []
for mod in (l.strip() for l in open(modlist)):
    if not mod:
        continue
    sym = obj_to_symbol(modmap[mod]) if mod in modmap else None
    if sym:
        wanted[sym] = 'y'
    else:
        unmapped.append(mod)
for k, v in load(extra).items():
    wanted[k] = v
print(f'{len(wanted)} requested options; no symbol for: {" ".join(unmapped)}')

deps = kconfig_deps()
with tempfile.TemporaryDirectory() as tmp:
    for rnd in range(12):
        frag = os.path.join(tmp, 'frag.config')
        with open(frag, 'w') as f:
            for k, v in sorted(wanted.items()):
                f.write(f'# CONFIG_{k} is not set\n' if v == 'n' else f'CONFIG_{k}={v}\n')
        subprocess.run(['scripts/kconfig/merge_config.sh', '-m', '-O', tmp, base, frag],
                       cwd=src, env=dict(os.environ, ARCH='arm64'), capture_output=True, check=True)
        subprocess.run(['make', '-s', f'O={tmp}', 'ARCH=arm64', 'LLVM=1', 'olddefconfig'],
                       cwd=src, capture_output=True, check=True)
        got = load(os.path.join(tmp, '.config'))
        missing = [k for k, v in wanted.items() if got.get(k, 'n') != v]
        added = []
        for k in missing:
            for d in deps.get(k, ()):
                if got.get(d) in ('m', 'n') and d not in wanted and d in deps or got.get(d) == 'm':
                    if d not in wanted and not d.startswith(('COMPILE_TEST', 'ARCH_')) or d.startswith('ARCH_QCOM'):
                        wanted[d] = 'y'
                        added.append(d)
        print(f'round {rnd}: {len(missing)} not applied, added {len(added)} dependencies')
        if not missing or not added:
            break
    with open(out, 'w') as f:
        f.write('# Generated by tools/kfrag.py: drivers the HP Googlebook needs built in\n'
                '# (bound at boot with the rescue initramfs), plus their dependencies.\n')
        for k, v in sorted(wanted.items()):
            f.write(f'# CONFIG_{k} is not set\n' if v == 'n' else f'CONFIG_{k}={v}\n')
    if missing:
        print('still not applied:', ' '.join(f'{k}(={got.get(k, "n")})' for k in missing))
